import {
  createDefaultPose,
  type Pose,
} from './PoseEngine';

export type MovePhase = 'STARTUP' | 'ACTIVE' | 'RECOVERY' | 'FINISH';

export type AttackLevel = 'LIGHT' | 'MEDIUM' | 'HEAVY' | 'SPECIAL';

export interface MoveCameraRequest {
  zoom?: number;
  shake?: number;
  shakeDir?: [number, number];
  slowMo?: number;
  duration?: number;
  track?: boolean;
  wide?: boolean;
}

export interface MoveVFXRequest {
  type: 'slash' | 'burst' | 'shockwave' | 'arc' | 'energy' | 'launch' | 'slam' | 'spark';
  origin: 'hand_l' | 'hand_r' | 'foot_l' | 'foot_r' | 'torso' | 'ground' | 'center';
  color: string;
  intensity: number;
  radius?: number;
}

export interface MoveDefinition {
  id: string;
  name: string;
  level: AttackLevel;
  state: string;
  startup: number;
  active: number;
  recovery: number;
  total: number;
  damage: number;
  hitstun: number;
  knockback: number;
  launchPower: number;
  groundBounce: number;
  range: number;
  forwardMovement: number;
  cancelWindow: number;
  camera?: MoveCameraRequest;
  vfx?: MoveVFXRequest;
  pose: Pose;
  combo?: string[];
  finisher?: boolean;
  hitOrigin?: string;
}

export type MoveRegistry = Record<string, MoveDefinition>;

export type { Pose };

/** Build a pose from default by overriding joint angles (radians) and optional root. */
export function makePose(
  angles: Partial<Record<string, number>>,
  root?: { x?: number; y?: number },
): Pose {
  const pose = createDefaultPose();
  for (const [name, angle] of Object.entries(angles)) {
    if (pose.joints[name] && angle !== undefined) {
      pose.joints[name].angle = angle;
    }
  }
  if (root) {
    pose.root.x = root.x ?? pose.root.x;
    pose.root.y = root.y ?? pose.root.y;
  }
  return pose;
}

function move(
  partial: Omit<MoveDefinition, 'total'> & { total?: number },
): MoveDefinition {
  const total =
    partial.total ??
    partial.startup + partial.active + partial.recovery;
  return { ...partial, total };
}

